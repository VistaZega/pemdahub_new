<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class VirtualLab extends Model
{
    protected $table = 'virtual_labs';

    protected $fillable = [
        'title',
        'slug',
        'category',
        'room_key',
        'subject_name',
        'engine_type',
        'description',
        'sop_steps',
        'custom_html',
        'course_id',
        'created_by',
        'icon',
        'accent_color',
        'is_active',
    ];

    protected $casts = [
        'sop_steps' => 'array',
        'is_active' => 'boolean',
    ];

    public function course()
    {
        return $this->belongsTo(LmsCourse::class, 'course_id');
    }

    public function creator()
    {
        return $this->belongsTo(User::class, 'created_by');
    }

    /**
     * Pengelompokan standar berdasarkan Rumpun Ilmu / Jenis Laboratorium.
     */
    public function getDisciplineKeyAttribute(): string
    {
        if (!empty($this->room_key)) {
            return $this->room_key;
        }

        $eng = strtolower((string) $this->engine_type);
        $subj = strtolower((string) $this->subject_name . ' ' . (string) $this->title);

        // 1. Cek engine bawaan terlebih dahulu secara ketat agar label UTBK/SMK di judul tidak menggeser mapel inti ke ruangan lain
        if (in_array($eng, ['olympiad_5', 'ptn_speed', 'ptn_speed_advanced', 'ptn_reasoning', 'ptn_spatial_3d'])) {
            return 'olimpiade';
        }
        if (in_array($eng, ['gasoline_engine', 'beam_load', 'subnetting', 'logic_gate', 'vokasi_plc', 'vokasi_lan_topo', 'vokasi_cad_dpib', 'vokasi_caliper', 'vokasi_electronics', 'vokasi_gears'])) {
            return 'vokasi';
        }
        if (in_array($eng, ['quadratic_graph', 'math_statistics', 'math_trigonometry', 'math_probability', 'math_transform', 'math_integral', 'math_trig_circle', 'math_derivative', 'math_sequences', 'math_linear_prog', 'math_vectors', 'math_exp_matrix'])) {
            return 'matematika';
        }
        if (in_array($eng, ['chemical_reaction', 'chem_ph', 'chem_atom', 'chem_stoichiometry', 'chem_titration', 'chem_voltaic', 'chem_equilibrium', 'chem_vsepr', 'biology_cell', 'bio_photosynthesis', 'bio_blood', 'bio_genetics', 'bio_osmosis', 'bio_nervous', 'bio_enzyme', 'bio_respiration', 'bio_protein_synthesis'])) {
            return 'kimia_biologi';
        }
        if (in_array($eng, ['sociology_dynamics', 'language_syntax', 'lang_indo_discourse', 'lang_english_snbt', 'econ_market', 'econ_compound', 'econ_inflation', 'econ_accounting', 'geo_tectonics'])) {
            return 'ips_bahasa';
        }
        if (in_array($eng, ['physics_motion', 'physics_parabola', 'physics_wave', 'physics_archimedes', 'physics_doppler', 'physics_pulley', 'physics_optics', 'physics_elevator', 'physics_electric_field', 'physics_pendulum', 'physics_calorimetry', 'physics_faraday', 'physics_pascal', 'physics_kepler', 'physics_thermo_pv', 'physics_bernoulli', 'physics_collision', 'physics_quantum_decay', 'ipa_greenhouse', 'ipa_renewable', 'ohm_law'])) {
            return 'fisika';
        }

        // 2. Fallback berbasis kata kunci untuk simulator kustom AI (ai_custom_html)
        if (str_contains($subj, 'olimpiade') || str_contains($subj, 'ptn') || str_contains($subj, 'snbt') || str_contains($subj, 'utbk')) {
            return 'olimpiade';
        }
        if ($this->category === 'vokasi' || str_contains($subj, 'smk') || str_contains($subj, 'tkj') || str_contains($subj, 'tkr') || str_contains($subj, 'dpib')) {
            return 'vokasi';
        }
        if (str_contains($subj, 'matematika') || str_contains($subj, 'gradien') || str_contains($subj, 'aljabar') || str_contains($subj, 'geometri') || str_contains($subj, 'kalkulus')) {
            return 'matematika';
        }
        if (str_contains($subj, 'kimia') || str_contains($subj, 'biologi')) {
            return 'kimia_biologi';
        }
        if (str_contains($subj, 'ekonomi') || str_contains($subj, 'sosiologi') || str_contains($subj, 'bahasa') || str_contains($subj, 'geografi') || str_contains($subj, 'akuntansi')) {
            return 'ips_bahasa';
        }

        return 'fisika';
    }

    public function getDisciplineLabelAttribute(): string
    {
        return match ($this->discipline_key) {
            'olimpiade'     => 'Lab Olimpiade & PTN',
            'fisika'        => 'Lab IPA & Fisika',
            'kimia_biologi' => 'Lab Kimia & Biologi',
            'matematika'    => 'Lab Matematika',
            'vokasi'        => 'Lab Kejuruan & Vokasi',
            'ips_bahasa'    => 'Lab IPS, Ekonomi & Bahasa',
            default         => 'Lab Riset Umum',
        };
    }

